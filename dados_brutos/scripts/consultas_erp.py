"""As consultas ao ERP da camada bruta (ODBC, um DSN por revenda, no projeto
original). Mantidas aqui como REFERENCIA -- nada neste arquivo e' executado na
demonstracao.

Os nomes de tabela e coluna do ERP foram trocados por nomes GENERICOS e legiveis
(ERP_CLIENTES, CLI_RAZAO_SOCIAL, PED_NUMERO, ITE_QTD...); a logica de cada
consulta (filtros, CASE, agregacoes, juncoes) e' a do original.

Os Parquet de origem (`dados/origem/erp/<revenda>/<consulta>.parquet`, gerados
por `dados/gerar_dados_ficticios.py`) tem exatamente as colunas que cada
consulta abaixo devolve (os aliases do SELECT). A chave de cada dicionario em
POR_ARQUIVO e' o nome do arquivo.

Placeholders: {d} (sufixo das tabelas da revenda: 01, 02...), {p} (sufixo da
tabela de produto, que nem sempre e' o mesmo), {hoje} (AAAAMMDD), {aamm}/{mm}
(tabelas mensais do livro fiscal e do kardex), {dd} (dia), {clausula} (recorte
de mes montado em Python), {cnpjs_outras} (as outras revendas, pra
transferencia entre filiais nao contar como emprestimo).
"""

CLIENTES = """
SELECT
    SUBSTRING(CAST(CLI_CNPJ_CPF AS VARCHAR(20)), LENGTH(CAST(CLI_CNPJ_CPF AS VARCHAR(20)))-5, 4) AS CGC_CPF,
    CLI_FANTASIA AS FANTASIA,
    CLI_CNPJ_CPF AS CHAVE,
    SUBSTRING(CAT_NOME, 1, 13) AS CANAL,
    CAT_CODIGO AS COD_CATEGORIA,
    SUBSTRING(CLI_MUNICIPIO_COB, 1, 15) AS CIDADE,
    CAST(CLI_REGIAO AS VARCHAR(4)) || RIGHT('000' || LTRIM(RTRIM(CAST(CLI_NUMERO AS VARCHAR(4)))), 4) AS CODCLI,
    CASE
        WHEN CLI_PORTE = 'D' THEN 'Diamante'
        WHEN CLI_PORTE = 'O' THEN 'Ouro'
        WHEN CLI_PORTE = 'P' THEN 'Prata'
        WHEN CLI_PORTE = 'B' THEN 'Bronze' ELSE 'S/Definicao'
    END AS PORTE,
    CASE
        WHEN CLI_PORTE = 'D' THEN 2.5
        WHEN CLI_PORTE = 'O' THEN 2
        WHEN CLI_PORTE = 'P' THEN 1.7
        WHEN CLI_PORTE = 'B' THEN 1.4 ELSE 1.4
    END AS ACRESCIMO,
    CLI_VENDEDOR AS VEN,
    SUBSTRING(CLI_RAZAO_SOCIAL, 1, 30) AS NOME,
    CLI_TIPO_COBRANCA AS TPCOBRANCA,
    CLI_COND_PAGTO AS CPG,
    CLI_BANCO AS BANCO,
    CLI_LIMITE_CREDITO AS LIMITE_CREDITO,
    (RTRIM(CLI_END_TIPO) || ' ' || RTRIM(CLI_ENDERECO) || ', ' || RTRIM(CAST(CLI_END_NUMERO AS VARCHAR(4))) || ' - '
        || RTRIM(CLI_BAIRRO) || ' - ' || RTRIM(CLI_MUNICIPIO) || ' - ' || RTRIM(CLI_UF)) AS ENDERECO,
    RTRIM(CLI_CONTATO) AS CONTATO,
    RTRIM(CLI_PONTO_REF) AS PTO_REF,
    RTRIM(CAST(CLI_DIA_VISITA AS VARCHAR(4))) AS DIA_VISIT,
    RTRIM(CAST(CLI_SEQ_VISITA AS VARCHAR(4))) AS SEQ,
    RTRIM(CAST(CLI_CEP AS VARCHAR(10))) AS CEP,
    RTRIM(CAST(CLI_FONE AS VARCHAR(20))) AS FONE,
    CLI_PROPRIETARIO AS PROPRIETARIO,
    CLI_CPF_RESP AS CPF_PROP,
    CLI_NASC_PROP AS NASC_PROP,
    CLI_EMAIL AS EMAIL_PROP,
    CLI_DIA_VISITA AS QUINZENAL,
    CLI_LATITUDE AS LATITUDE,
    CLI_LONGITUDE AS LONGITUDE,
    MUN_IBGE AS COD_IBGE
FROM ERP_CLIENTES
INNER JOIN ERP_CATEGORIAS_CLIENTE ON CAT_CODIGO = CLI_CATEGORIA
LEFT JOIN ERP_MUNICIPIOS ON MUN_CODIGO = CLI_COD_MUNICIPIO
"""

PRODUTOS = """
SELECT
    RIGHT('0000' || CAST(PRD_FAMILIA AS VARCHAR(3)), 3) || RIGHT('0000' || CAST(PRD_NUMERO AS VARCHAR(3)), 3) AS CODCOMP,
    PRD_COD_REDUZIDO AS CODRED,
    PRD_DESCRICAO AS PRODUTO,
    RTRIM(PRD_DESCRICAO_GENERICA) AS PRODUTO_GENERICO,
    PRD_QTD_UNIDADE AS UNIDADE,
    PRD_MEDIDA AS LITRAGEM,
    G.GRP_DESCRICAO AS TIPO,
    PRD_TIPO AS TIPO_2,
    PRD_GRUPO AS GRUPO,
    PRD_NCM AS NCM,
    PRD_COMODATO AS CEV,
    PRD_COD_FORNECEDOR AS COD_PROD_FORN,
    M.MAR_DESCRICAO AS MARCA
FROM ERP_PRODUTOS_0{p} P
LEFT JOIN ERP_GRUPOS_PRODUTO_0{p} G ON G.GRP_CODIGO = P.PRD_GRUPO_GERENCIAL
LEFT JOIN ERP_MARCAS_0{p} M ON M.MAR_CODIGO = P.PRD_MARCA
"""

PRECO_PROD = """
SELECT
    RIGHT('0000' || CAST(TAB_FAMILIA AS VARCHAR(3)), 3) || RIGHT('0000' || CAST(TAB_NUMERO AS VARCHAR(3)), 3) AS CODCOMP,
    TAB_PRECO_UN AS PRECO_UN,
    TAB_PRECO AS PRECO,
    CAST(TAB_ANO AS VARCHAR(4)) || RIGHT('00' || CAST(TAB_MES AS VARCHAR(2)), 2) || CAST(TAB_NUM_TABELA AS VARCHAR(2)) AS TAB_CEV
FROM ERP_TABELA_PRECOS_0{p}
WHERE TAB_NUM_TABELA = 99
  AND TAB_VIGENCIA_INI <= {hoje}
  AND TAB_VIGENCIA_FIM >= {hoje}
"""

# Uma consulta POR MES (so' a janela recente + mes que falta na base local), e
# mais uma avulsa com "WHERE PED_ROMANEIO = 0" (pedido ainda sem romaneio).
PEDIDOS = """
SELECT DISTINCT
    PED_NUMERO AS PEDIDO,
    PED_DT_EMISSAO AS DT,
    PED_ROMANEIO AS ROMANEIO,
    PED_CLIENTE AS CODCLI,
    PED_VENDEDOR AS COD_VENDEDOR,
    PED_TIPO_COBRANCA AS TIPO_COBRANCA,
    ITE_OCORRENCIA AS OCO,
    CASE WHEN PED_ORIGEM_COD = 'D' THEN 'ERP'
         WHEN PED_ORIGEM_COD = 'L' THEN 'Portal'
         WHEN PED_ORIGEM_COD IN ('P', 'R') THEN 'SFA'
         ELSE PED_ORIGEM_COD
    END AS PED_ORIGEM,
    PED_NF AS NOTA_FISCAL,
    PED_VALOR AS VALOR,
    NFS_CHAVE_ACESSO AS CHAVE_NFE,
    PED_VENCIMENTO AS VENC,
    PED_SITUACAO AS STATUS,
    PED_FORA_ROTA AS FORA_ROTA,
    PED_USUARIO AS REPROGRAMADO,
    CAST(BAI_DT_PAGAMENTO AS VARCHAR(8)) AS PAG
FROM ERP_PEDIDOS_0{d}
LEFT JOIN ERP_BAIXAS_0{d} ON BAI_PEDIDO = PED_NUMERO
LEFT JOIN ERP_NOTAS_FISCAIS_0{d} ON NFS_NUMERO = PED_NF
LEFT JOIN ERP_PEDIDO_ITENS_0{d} ON ITE_NUM_PEDIDO = PED_NUMERO
WHERE ({clausula})
"""

VEND_DEV_ITENS = """
SELECT
    I.ITE_NUM_PEDIDO AS COD_PED,
    P.PRD_COD_REDUZIDO AS CODR,
    P.PRD_DESCRICAO_GENERICA AS PRODUTO_GENERICO,
    I.ITE_CFOP AS CFOP,
    SUM(I.ITE_QTD) AS QTD,
    SUM(I.ITE_QTD_DEVOLVIDA) AS DEVOLUCAO_CX,
    SUM(I.ITE_QTD_UN) AS QTDS,
    SUM(CASE WHEN I.ITE_OCORRENCIA IN (1, 60) THEN I.ITE_VALOR_TOTAL ELSE 0 END) AS "VALOR VENDA",
    SUM(CASE WHEN I.ITE_OCORRENCIA IN (1, 60) THEN I.ITE_VALOR_DEVOLVIDO ELSE 0 END) AS "VALOR DEVOLUCAO",
    SUM(CASE WHEN I.ITE_OCORRENCIA IN (2, 4) THEN I.ITE_VALOR_TOTAL ELSE 0 END) AS VALOR_BONIF,
    SUM(CASE WHEN I.ITE_OCORRENCIA IN (2, 4) THEN I.ITE_VALOR_DEVOLVIDO ELSE 0 END) AS VALOR_BONIF_DEV,
    SUM(CASE WHEN I.ITE_OCORRENCIA IN (2, 4) THEN I.ITE_QTD ELSE 0 END) AS QTD_BONIF,
    SUM(CASE WHEN I.ITE_OCORRENCIA IN (2, 4) THEN I.ITE_QTD_UN ELSE 0 END) AS QTDS_BONIF
FROM ERP_PRODUTOS_0{p} AS P
INNER JOIN ERP_PEDIDO_ITENS_0{d} AS I ON P.PRD_COD_REDUZIDO = I.ITE_COD_PRODUTO
WHERE ({clausula})
GROUP BY I.ITE_NUM_PEDIDO, P.PRD_COD_REDUZIDO, P.PRD_DESCRICAO_GENERICA, I.ITE_CFOP
"""

TITULOS_ABERTOS = """
SELECT
    TIT_CLIENTE AS CODCLI,
    TIT_VENDEDOR AS VEN,
    TIT_VENCIMENTO AS TITULO_MAIS_ANTIGO,
    SUM(TIT_VALOR) AS VALOR
FROM ERP_TITULOS_0{d}
WHERE TIT_MODALIDADE = 4
GROUP BY TIT_CLIENTE, TIT_VENDEDOR, TIT_VENCIMENTO
"""

CEV = """
SELECT
    CAST(CMP_CLIENTE AS VARCHAR(8)) AS CODCLI,
    CMP_PRODUTO AS CODCOMP,
    CMP_CONTRATO AS CEV,
    CMP_MOTIVO AS MOT,
    CMP_DT_EMISSAO AS DTE,
    CMP_DT_VENC AS DTV,
    CMP_QTD AS QTD,
    CMP_NF AS NF,
    CMP_SERIE AS SERIE,
    CAST(CMP_PEDIDO AS VARCHAR(12)) AS NPED,
    PRE_PEDIDO AS PRE_PED,
    CMP_ROMANEIO AS ROMA,
    CMP_TIPO AS TIPO,
    'PENDENTE' AS STATUS
FROM ERP_COMODATO_PENDENTE_0{d}
LEFT JOIN ERP_PRE_PEDIDOS ON PRE_NUM_PEDIDO = CMP_PEDIDO
WHERE CAST(SUBSTRING(CAST(CMP_PEDIDO AS VARCHAR(12)), 1, 6) AS INT) >= 202001
"""

# Pula domingo/feriado e, sem lancamento no dia, tenta ate' 2 dias uteis antes.
ESTOQUE = """
SELECT
    KAR_PRODUTO AS CODCOMP,
    CASE WHEN ((KAR_SALDO_INICIAL + KAR_ENTRADAS) - KAR_SAIDAS) > 0 THEN 'SIM' ELSE 'NAO' END AS ESTOQUE
FROM ERP_KARDEX_DIA_{aamm}_0{d}
WHERE KAR_DIA = {dd}
  AND ((KAR_SALDO_INICIAL + KAR_ENTRADAS) - KAR_SAIDAS) > 0
"""

# Livro fiscal de vasilhame, mes a mes desde 2025-01. PRODUTO com CAST: sem ele
# a coluna virava inteiro e quebrava a camada intermediaria mais adiante
# ('is_in' cannot check for List(String) values in Int64 data).
LIVRO_ENTRADA = """
SELECT
    I.FIS_NF AS NF,
    CASE WHEN E.FSE_CFOP IN (1553, 2553) THEN 'Dev Venda' ELSE 'Dev Emprestimo' END AS operacao,
    E.FSE_DT_ENTRADA AS DATA,
    E.FSE_CLIENTE AS CLI,
    CAST(I.FIS_PRODUTO AS VARCHAR(12)) AS PRODUTO,
    RTRIM(P.PRD_DESCRICAO_GENERICA) AS PRODUTO_GENERICO,
    I.FIS_QTD AS QTD,
    I.FIS_QTD_UN AS QTDS,
    C.CLI_VENDEDOR AS VEN
FROM ERP_FISCAL_ITENS_{aamm}{mm}_0{d} I
INNER JOIN ERP_FISCAL_ENTRADAS_{aamm}{mm}_0{d} E
    ON I.FIS_NF = E.FSE_NF AND E.FSE_CFOP = I.FIS_CFOP
LEFT JOIN ERP_CLIENTES C
    ON CAST(C.CLI_REGIAO AS VARCHAR(4)) || RIGHT('000' || LTRIM(RTRIM(CAST(C.CLI_NUMERO AS VARCHAR(4)))), 4) = CAST(E.FSE_CLIENTE AS VARCHAR(8))
LEFT JOIN ERP_PRODUTOS_0{p} P
    ON RIGHT('0000' || CAST(P.PRD_FAMILIA AS VARCHAR(3)), 3) || RIGHT('0000' || CAST(P.PRD_NUMERO AS VARCHAR(3)), 3) = CAST(I.FIS_PRODUTO AS VARCHAR(12))
WHERE E.FSE_CFOP IN (1553, 2553, 1909, 2909)
  AND I.FIS_CNPJ_EMITENTE NOT IN ({cnpjs_outras})
"""

LIVRO_SAIDA = """
SELECT
    I.FIS_NF AS NF,
    CASE WHEN S.FSA_CFOP IN (5551, 6551) THEN 'Vendi' ELSE 'Emprestei' END AS operacao,
    CAST(S.FSA_ANO AS VARCHAR(4)) || RIGHT('0' || CAST(S.FSA_MES AS VARCHAR(2)), 2) || RIGHT('0' || CAST(S.FSA_DIA AS VARCHAR(2)), 2) AS DATA,
    S.FSA_CLIENTE AS CLI,
    CAST(I.FIS_PRODUTO AS VARCHAR(12)) AS PRODUTO,
    RTRIM(P.PRD_DESCRICAO_GENERICA) AS PRODUTO_GENERICO,
    I.FIS_QTD AS QTD,
    I.FIS_QTD_UN AS QTDS,
    C.CLI_VENDEDOR AS VEN
FROM ERP_FISCAL_ITENS_{aamm}{mm}_0{d} I
INNER JOIN ERP_FISCAL_SAIDAS_{aamm}{mm}_0{d} S
    ON I.FIS_NF = S.FSA_NF AND S.FSA_CFOP = I.FIS_CFOP
LEFT JOIN ERP_CLIENTES C
    ON CAST(C.CLI_REGIAO AS VARCHAR(4)) || RIGHT('000' || LTRIM(RTRIM(CAST(C.CLI_NUMERO AS VARCHAR(4)))), 4) = CAST(S.FSA_CLIENTE AS VARCHAR(8))
LEFT JOIN ERP_PRODUTOS_0{p} P
    ON RIGHT('0000' || CAST(P.PRD_FAMILIA AS VARCHAR(3)), 3) || RIGHT('0000' || CAST(P.PRD_NUMERO AS VARCHAR(3)), 3) = CAST(I.FIS_PRODUTO AS VARCHAR(12))
WHERE S.FSA_CFOP IN (5551, 6551, 6908, 5908)
  AND I.FIS_CNPJ_EMITENTE NOT IN ({cnpjs_outras})
"""

POR_ARQUIVO = {
    "clientes": CLIENTES,
    "produtos": PRODUTOS,
    "preco_prod": PRECO_PROD,
    "pedidos": PEDIDOS,
    "vend_dev_itens": VEND_DEV_ITENS,
    "titulos_abertos": TITULOS_ABERTOS,
    "cev": CEV,
    "estoque": ESTOQUE,
    "livro_entrada": LIVRO_ENTRADA,
    "livro_saida": LIVRO_SAIDA,
}
